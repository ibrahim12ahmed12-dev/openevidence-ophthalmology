"""SYNTHETIC demonstration data - NOT STUDY DATA.

Builds a complete, clearly labelled fake data root and drives it through the
real pipeline (schedule -> prompts -> collection log -> blinded packets ->
simulated grader returns -> merge -> adjudication -> analysis dataset) so the
R analysis, tables and figures can be exercised before any real collection.

Every case text, response and grade below is invented by a random-number
generator. No OpenEvidence output is generated or imitated: responses are
placeholder strings containing only the two answer-format lines. Simulated
effect sizes are arbitrary and carry no information about the real models.
"""
from __future__ import annotations

import datetime as dt
import json
import math
import random
import shutil
from pathlib import Path

from . import build as build_mod
from . import collection, grading, prompts, schedule
from .common import (cond_lookup, ensure_dirs, load_config, path, read_csv, sha256_file,
                     sha256_text, write_csv)
from .importer import (ANNOTATION_FIELDS, ANSWER_KEY_FIELDS, IMAGE_ARM_FIELDS, IMAGE_FIELDS,
                       REGISTRY_FIELDS)

# Subspecialty sizes mirror the real benchmark's composition (not sensitive).
SUBSPECIALTY_N = [("Retina and Vitreous", 96), ("Uveitis", 67), ("Neuro-ophthalmology", 67),
                  ("Pediatrics", 56), ("Pathology and Tumors", 43), ("Cornea", 39),
                  ("Oculoplastics", 31), ("Glaucoma", 12), ("Lens and cataract", 9), ("General Medicine", 2)]
MODALITIES = ["Fundus photography", "OCT", "Slit lamp / anterior segment", "Fluorescein / ICG angiography",
              "Visual fields", "CT / MRI", "External photography", "Histopathology"]
# Arbitrary SYNTHETIC log-odds effects (relative to Osler text-only)
SIM = {"dx_base": -0.15, "mgmt_base": 0.55, "case_sd": 1.3,
       "model": {"Osler": 0.0, "Sackett": 0.15, "Snow": 0.35},
       "image": {"Osler": -0.10, "Sackett": 0.0, "Snow": 0.10},
       "mgmt_given_dx": 0.9, "grader_flip": 0.05, "retrieval_p": {"Osler": 0.01, "Sackett": 0.02, "Snow": 0.05}}
PNG_1x1 = bytes.fromhex("89504e470d0a1a0a0000000d4948445200000001000000010806000000"
                        "1f15c4890000000d49444154789c6360000002000154a24f5d0000000049454e44ae426082")
BANNER = "SYNTHETIC DEMONSTRATION DATA - NOT STUDY DATA - NOT OPENEVIDENCE OUTPUT"


def _inv_logit(x):
    return 1 / (1 + math.exp(-x))


def build(out: str | Path, seed: int = 11) -> dict:
    out = Path(out)
    if out.exists():
        shutil.rmtree(out)
    ensure_dirs(out)
    rng = random.Random(seed)
    (out / "SYNTHETIC_DATA_README.md").write_text(
        f"# {BANNER}\n\nGenerated by `python -m oe synthetic --seed {seed}` on "
        f"{dt.date.today().isoformat()}.\n\nEvery value here is random. Case IDs reuse the real 2-423 range "
        "only so the real randomisation can be exercised; case content is fake. Never merge with data/.\n\n"
        "Planted features: 2 cases with video-only figures (image arms 'unavailable'), failed-then-retried "
        "attempts, responses without the answer-format lines, MULTIPLE/NONE management answers, a few "
        "source retrievals, grader disagreements resolved by a simulated adjudicator.\n", encoding="utf-8")
    (out / "config_override.json").write_text(json.dumps(
        {"collection": {"study_start_date": "2026-07-01"}}, indent=2), encoding="utf-8")
    cfg = load_config(out)
    ids = list(range(2, 424))
    subs = [s for s, n in SUBSPECIALTY_N for _ in range(n)]
    rng.shuffle(subs)
    subs.insert(232, "Pediatrics")  # case 234 is the synthetic excluded case (index 232)
    reg, keys, ann, arm, imgs, case_u, case_mods = [], [], [], [], [], {}, {}
    video_cases = {57, 311}
    for i, cid in enumerate(ids):
        eligible = cid != 234
        nfig = rng.choice([1, 1, 1, 2])
        text = (f"SYNTHETIC case {cid}. A fictional patient in their {rng.choice([3,4,5,6,7])}0s presented with "
                f"invented symptom {rng.randint(1, 99)} in the {rng.choice(['right', 'left'])} eye (Figure 1).\n"
                f" Further invented history item {rng.randint(1, 99)}.\n"
                f" A, SYNTHETIC figure legend describing invented finding {rng.randint(1, 99)} (arrowheads).")
        opts = "\n ".join(f"{L}. Synthetic management option {L}{cid}" for L in "ABCD")
        letter = rng.choice("ABCD")
        reg.append({"case_id": cid, "source_row": cid, "eligible": "Yes" if eligible else "No",
                    "exclusion_reason": "" if eligible else "SYNTHETIC exclusion (reason placeholder)",
                    "subspecialty": subs[i], "source_url": f"https://example.org/synthetic/{cid}",
                    "original_text": text, "leak_corrected_text": "", "leak_corrected_identical_to_original": "",
                    "text_only_input": text, "text_source": "E (original)", "answer_options": opts,
                    "n_options": 4, "options_sha256": sha256_text(opts), "text_only_sha256": sha256_text(text),
                    "retest_subset_workbook": ""})
        keys.append({"case_id": cid, "case_title": f"Synthetic Title {cid}",
                     "reference_diagnosis": f"Synthetic disorder {cid}", "correct_letter": letter,
                     "correct_letter_workbook": letter, "correct_letter_from_text": letter, "key_check": "OK",
                     "correct_answer_text": f"{letter}. Synthetic management option {letter}{cid}",
                     "answer_key_explanation": "", "discussion": f"SYNTHETIC discussion {cid}."})
        ann.append({"case_id": cid, "publication_year": rng.randint(2013, 2025),
                    "accepted_dx_synonyms": f"Synthetic disorder {cid}; SD-{cid}",
                    "synonyms_finalized_by": "SYN", "synonyms_finalized_date": "2026-07-15", "n_figures": nfig})
        img_text = text.split("\n A, ")[0].replace("(Figure 1)", "(Figure 1 attached)")
        arm.append({"case_id": cid, "image_arm_text": img_text, "status": "approved",
                    "edited_by": "SYN", "approved_by": "SYN-REVIEWER", "approved_date": "2026-07-20"})
        mods = rng.sample(MODALITIES, rng.choice([1, 1, 2]))
        case_mods[cid] = mods
        for f in range(1, nfig + 1):
            iid = f"IMG-{cid:03d}-{f}"
            av = "unavailable_video_only" if cid in video_cases else "available"
            imgs.append({"case_id": cid, "image_id": iid, "figure_number": f, "panels": "A",
                         "original_filename": f"synthetic_original_{cid}_{f}.png",
                         "prepared_filename": f"{iid}.png" if av == "available" else "",
                         "modality": mods[(f - 1) % len(mods)] if f > 1 else ";".join(mods), "availability": av,
                         "unavailable_reason": "video-only figure (synthetic)" if av != "available" else "",
                         "preparation_steps": "synthetic placeholder", "label_or_caption_flag": "cleared",
                         "label_review_by": "SYN"})
        case_u[cid] = rng.gauss(0, SIM["case_sd"])
    write_csv(path(out, "registry"), reg, REGISTRY_FIELDS)
    write_csv(path(out, "answer_key"), keys, ANSWER_KEY_FIELDS)
    write_csv(path(out, "annotations"), ann, ANNOTATION_FIELDS)
    write_csv(path(out, "image_arm"), arm, IMAGE_ARM_FIELDS)
    prep = out / "images" / "prepared"
    prep.mkdir(parents=True, exist_ok=True)
    for im in imgs:
        if im["prepared_filename"]:
            (prep / im["prepared_filename"]).write_bytes(PNG_1x1)
            im["prepared_sha256"] = sha256_file(prep / im["prepared_filename"])
    write_csv(path(out, "images"), imgs, IMAGE_FIELDS)
    lock = [{"case_id": r["case_id"], "eligible": r["eligible"], "options_sha256": r["options_sha256"],
             "text_only_sha256": r["text_only_sha256"], "title_sha256": sha256_text(k["case_title"]),
             "correct_letter": k["correct_letter"], "locked_by": "SYN", "locked_at": "2026-07-21T00:00:00"}
            for r, k in zip(reg, keys)]
    write_csv(path(out, "registry_lock"), lock)

    schedule.build(out)
    prompts.generate(out)
    collection.init_log(out)
    sched = read_csv(path(out, "schedule"))
    prom = {(p["case_id"], p["input"]): p for p in read_csv(out / "prompts" / f"prompts_{cfg['prompt']['active_version']}.csv")}
    keyd = {str(k["case_id"]): k for k in keys}
    cl = cond_lookup(cfg)
    base = dt.datetime(2026, 8, 3, 9, 0)
    rows, truth = [], {}
    case_day = {}
    for s in sched:
        cid = int(s["case_id"])
        k = int(s["condition"])
        model, inp = cl[k]["model"], cl[k]["input"]
        day = case_day.setdefault((s["run_type"], cid), (cid % 25) + (21 if s["run_type"] == "Retest" else 0))
        when = base + dt.timedelta(days=day, minutes=10 * int(s["run_order"]) + rng.randint(0, 5))
        helper = {h: s[h] for h in collection.HELPER}
        common = {"run_id": s["run_id"], **helper, "collector": f"SYN-C{cid % 6 + 1}",
                  "prompt_version": cfg["prompt"]["active_version"], "timezone": "America/New_York",
                  "model_selection_confirmed": "Yes", "new_session_confirmed": "Yes", "memory_personalization_off": "Yes"}
        if inp == "text_image" and cid in video_cases:
            rows.append({**common, "attempt_no": 1, "status": "unavailable",
                         "failure_reason": "figure is video-only; cannot be uploaded (synthetic)"})
            continue
        att = 1
        if rng.random() < 0.01:
            rows.append({**common, "attempt_no": 1, "status": "failed", "failure_reason": "synthetic platform error",
                         "run_date": when.strftime("%Y-%m-%d"), "run_time": when.strftime("%H:%M")})
            att = 2
            when += dt.timedelta(minutes=30)
        eta = SIM["model"][model] + (SIM["image"][model] if inp == "text_image" else 0) + case_u[cid]
        dx = int(rng.random() < _inv_logit(SIM["dx_base"] + eta))
        mg = int(rng.random() < _inv_logit(SIM["mgmt_base"] + 0.6 * eta + SIM["mgmt_given_dx"] * (dx - 0.5)))
        key = keyd[str(cid)]["correct_letter"]
        letter = key if mg else rng.choice([x for x in "ABCD" if x != key])
        style = rng.random()
        if style < 0.01:
            ns_line, letter_code = f"Next step: {letter} or {rng.choice('ABCD')}", "MULTIPLE"
            mg = 0
        elif style < 0.015:
            ns_line, letter_code = "Next step: further evaluation", "NONE"
            mg = 0
        else:
            ns_line, letter_code = f"Next step: {letter}", letter
        dx_text = f"Synthetic disorder {cid}" if dx else f"Synthetic other disorder {rng.randint(1, 999)}"
        if rng.random() < 0.03:
            resp = f"{BANNER}\nPlaceholder narrative without the answer-format lines. The answer appears to be {letter_code}."
        else:
            resp = f"Diagnosis: {dx_text}\n{ns_line}\n{BANNER}\nPlaceholder explanation text."
        dur = {"Osler": rng.uniform(3, 12), "Sackett": rng.uniform(20, 60), "Snow": rng.uniform(150, 480)}[model]
        retrieved = "Yes" if rng.random() < SIM["retrieval_p"][model] else "No"
        p = prom.get((str(cid), inp), {})
        rows.append({**common, "attempt_no": att, "status": "completed",
                     "prompt_sha256": p.get("prompt_sha256", ""),
                     "run_date": when.strftime("%Y-%m-%d"), "run_time": when.strftime("%H:%M"),
                     "response_duration_s": round(dur, 1),
                     "image_ids_uploaded": p.get("image_ids_to_upload", "") if inp == "text_image" else "",
                     "n_images_uploaded": len([x for x in p.get("image_ids_to_upload", "").split(";") if x]) if inp == "text_image" else "",
                     "response_text": resp, "screenshot_path": f"screenshots/{s['run_id']}.png",
                     "citation_count": rng.randint(2, 12) + (8 if model == "Snow" else 0),
                     "source_retrieved": retrieved, "retrieval_assessed_by": "SYN-C1"})
        truth[s["run_id"]] = {"dx": dx, "mg": mg, "letter": letter_code,
                              "partial": int((not dx) and rng.random() < 0.3),
                              "interp": rng.choice(grading.INTERP_CATEGORIES[:4]) if inp == "text_image" else ""}
    write_csv(path(out, "collection"), rows, collection.FIELDS)

    grading.make_packets(out, ("G1", "G2"), seed=seed, batch="SYN001")
    rkey = {k["response_id"]: k["run_id"] for k in read_csv(path(out, "response_key"))}
    for g in ("G1", "G2"):
        for kind in ("grader", "interp"):
            pf = out / "grading" / "packets" / f"{'grader' if kind == 'grader' else 'interp'}_{g}_batch_SYN001.csv"
            prow = read_csv(pf)
            for r in prow:
                t = truth[rkey[r["response_id"]]]
                flip = lambda v: (1 - v) if rng.random() < SIM["grader_flip"] else v
                r["graded_date"] = "2026-09-20"
                if kind == "grader":
                    r["extracted_diagnosis_confirmed"] = r["auto_diagnosis"] or "(read from full response)"
                    r["dx_correct"] = flip(t["dx"])
                    r["dx_partial"] = t["partial"] if r["dx_correct"] == 0 else 0
                    r["dx_reason"] = "synthetic"
                    r["mgmt_letter"] = t["letter"]
                    r["mgmt_correct"] = t["mg"]
                    r["mgmt_reason"] = "synthetic"
                else:
                    r["interp_category"] = t["interp"] if rng.random() > 0.1 else rng.choice(grading.INTERP_CATEGORIES)
                    r["interp_reason"] = "synthetic"
            write_csv(out / "grading" / "returns" / pf.name, prow)
    # one deliberate management-letter disagreement path: grader 2 misreads a few letters
    g2f = out / "grading" / "returns" / "grader_G2_batch_SYN001.csv"
    g2 = read_csv(g2f)
    for r in g2[:: max(1, len(g2) // 40)]:
        if r["mgmt_letter"] in "ABCD" and r["mgmt_letter"]:
            wrong = [x for x in "ABCD" if x != r["mgmt_letter"]][0]
            r["mgmt_letter"] = wrong
            r["mgmt_correct"] = int(wrong == r["correct_letter"])
    write_csv(g2f, g2)
    grading.merge(out)
    adj = read_csv(path(out, "adjudication_packet"))
    for a in adj:
        t = truth[rkey[a["response_id"]]]
        a.update({"adjudicator_id": "SYN-ADJ", "adj_dx_correct": t["dx"], "adj_dx_partial": t["partial"],
                  "adj_mgmt_correct": t["mg"], "adj_interp_category": t["interp"] or "",
                  "adj_reason": "synthetic adjudication"})
    write_csv(path(out, "adjudication_return"), adj)
    res = grading.merge(out)
    b = build_mod.build(out)
    return {"root": str(out), "banner": BANNER, "merge": res, "analysis_rows": b["rows"],
            "analyzable_dx_main": b["analyzable_dx_main"]}
